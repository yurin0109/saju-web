    /** 이 단어 바로 뒤에 오면 "아니다"라는 뜻으로 보고 세지 않는다 (예: "이직은 안 할 거예요") */
    private static final List<String> NEGATIONS = List.of("안할", "안 할", "안해", "않", "말고", "아니에요", "아니야", "아님", "생각없", "생각 없", "관심없", "관심 없");

    /**
     * 고민 문장에서 맞는 세부 주제를 찾는다.
     * 1) 고른 분류 안에서 단어가 가장 많이 맞는 주제
     * 2) 하나도 안 맞으면 다른 분류의 주제까지 찾아본다 (예: 분류는 '연애'인데 '이직' 이야기를 쓴 경우)
     * 3) 그래도 없으면 고른 분류의 기본 주제
     */
    static Topic match(String type, String text) {
        if (type == null) return null;
        List<Topic> topics = TOPICS.get(type);
        if (topics == null) return null;
        Topic fallback = topics.get(topics.size() - 1);
        if (text == null || text.isBlank()) return fallback;
        String t = text.replace(" ", "").toLowerCase();

        Topic best = null;
        int bestScore = 0;
        for (Topic topic : topics) {
            int sc = score(topic, t);
            if (sc > bestScore) { best = topic; bestScore = sc; }
        }
        if (best != null) return best;

        for (Map.Entry<String, List<Topic>> e : TOPICS.entrySet()) {
            if (e.getKey().equals(type)) continue;
            for (Topic topic : e.getValue()) {
                int sc = score(topic, t);
                if (sc > bestScore) { best = topic; bestScore = sc; }
            }
        }
        return best != null ? best : fallback;
    }

    /** 고른 분류 안에서만 찾기 (여러 분류를 골랐을 때 서로 같은 주제가 나오지 않게) */
    static Topic matchWithin(String type, String text) {
        if (type == null) return null;
        List<Topic> topics = TOPICS.get(type);
        if (topics == null) return null;
        Topic fallback = topics.get(topics.size() - 1);
        if (text == null || text.isBlank()) return fallback;
        String t = text.replace(" ", "").toLowerCase();
        Topic best = null;
        int bestScore = 0;
        for (Topic topic : topics) {
            int sc = score(topic, t);
            if (sc > bestScore) { best = topic; bestScore = sc; }
        }
        return best != null ? best : fallback;
    }

    static int scoreText(Topic topic, String text) {
        return text == null ? 0 : score(topic, text.replace(" ", "").toLowerCase());
    }

    /** 맞는 단어 수 (부정 표현이 바로 뒤따르는 단어는 빼고) */
    static int score(Topic topic, String compactText) {
        int n = 0;
        for (String k : topic.keywords()) {
            String key = k.replace(" ", "").toLowerCase();
            if (key.length() < 2) continue;   // 한 글자 단어는 엉뚱하게 걸리기 쉬워서 뺀다
            int at = compactText.indexOf(key);
            while (at >= 0) {
                String after = compactText.substring(at + key.length(), Math.min(compactText.length(), at + key.length() + 6));
                boolean negated = NEGATIONS.stream().anyMatch(neg -> after.contains(neg.replace(" ", "")));
                if (!negated) { n++; break; }
                at = compactText.indexOf(key, at + 1);
            }
        }
        return n;
    }
